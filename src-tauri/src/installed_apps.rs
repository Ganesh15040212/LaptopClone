use serde::{Deserialize, Serialize};
use std::collections::HashSet;
use winreg::enums::*;
use winreg::RegKey;

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct AppItem {
    pub id: String,
    pub name: String,
    pub version: String,
    pub publisher: String,
}

const UNINSTALL_PATH: &str = "SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Uninstall";

#[tauri::command]
pub fn scan_installed_apps() -> Result<Vec<AppItem>, String> {
    collect_installed_apps().map_err(|e| e.to_string())
}

fn collect_installed_apps() -> Result<Vec<AppItem>, Box<dyn std::error::Error>> {
    let mut apps: Vec<AppItem> = Vec::new();
    let mut seen: HashSet<String> = HashSet::new();

    // HKLM
    let hklm = RegKey::predef(HKEY_LOCAL_MACHINE);
    if let Ok(key) = hklm.open_subkey(UNINSTALL_PATH) {
        collect_from_key(&key, &mut apps, &mut seen);
    }

    // HKCU
    let hkcu = RegKey::predef(HKEY_CURRENT_USER);
    if let Ok(key) = hkcu.open_subkey(UNINSTALL_PATH) {
        collect_from_key(&key, &mut apps, &mut seen);
    }

    Ok(apps)
}

fn collect_from_key(key: &RegKey, apps: &mut Vec<AppItem>, seen: &mut HashSet<String>) {
    // If this key itself describes an application, record it.
    if let Ok(name) = key.get_value::<_, String>("DisplayName") {
        if !name.trim().is_empty() {
            let version = key
                .get_value::<_, String>("DisplayVersion")
                .unwrap_or_default();
            let publisher = key
                .get_value::<_, String>("Publisher")
                .unwrap_or_default();

            // Skip system components and child MSI components.
            let system_component: u32 = key.get_value::<_, u32>("SystemComponent").unwrap_or(0);
            let has_parent: Result<String, _> = key.get_value::<_, String>("ParentKeyName");

            if system_component != 1
                && has_parent.is_err()
                && !is_filtered(&name)
            {
                let slug = slugify(&name);
                let id = if slug.is_empty() {
                    name.clone()
                } else {
                    slug
                };
                let dedup_key = format!("{}|{}|{}", name, version, publisher);
                if seen.insert(dedup_key) {
                    apps.push(AppItem {
                        id,
                        name,
                        version,
                        publisher,
                    });
                }
            }
        }
    }

    // Recurse into all subkeys.
    if let Ok(subkeys) = key.enum_keys() {
        for subkey_name in subkeys.flatten() {
            if let Ok(subkey) = key.open_subkey(&subkey_name) {
                collect_from_key(&subkey, apps, seen);
            }
        }
    }
}

fn is_filtered(name: &str) -> bool {
    let lower = name.to_lowercase();

    // System updates / patches / language packs.
    let blocked_substrings = [
        "update",
        "hotfix",
        "security update",
        "service pack",
        "language pack",
        "languagepack",
        "lang pack",
    ];
    if blocked_substrings.iter().any(|b| lower.contains(b)) {
        return true;
    }

    // KB patches, e.g. "KB5034441" or "Update for ... (KB123456)".
    if is_kb_patch(&lower) {
        return true;
    }

    false
}

fn is_kb_patch(text: &str) -> bool {
    if let Some(pos) = text.find("kb") {
        let rest = &text[pos + 2..];
        let digit_count = rest.chars().take_while(|c| c.is_ascii_digit()).count();
        digit_count > 0
            && rest
                .chars()
                .next()
                .map(|c| c.is_ascii_digit())
                .unwrap_or(false)
    } else {
        false
    }
}

fn slugify(input: &str) -> String {
    let mut out = String::new();
    let mut last_dash = false;
    for c in input.chars() {
        if c.is_alphanumeric() {
            out.push(c.to_ascii_lowercase());
            last_dash = false;
        } else if !last_dash {
            out.push('-');
            last_dash = true;
        }
    }
    out.trim_matches('-').to_string()
}

/// Generate a PowerShell script containing winget install commands.
pub fn generate_winget_script(apps: &[AppItem]) -> String {
    let mut script = String::new();
    script.push_str("# Auto-generated by LaptopClone\n");
    script.push_str("# Requires winget to be installed.\n\n");

    for app in apps {
        script.push_str(&format!(
            "winget install --id {} --silent\n",
            app.id
        ));
    }

    script
}
